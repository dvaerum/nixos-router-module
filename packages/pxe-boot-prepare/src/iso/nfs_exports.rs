//! `exports(5)` file for the mounted ISOs, one export per ISO.
//!
//! One export per ISO (not a single `crossmnt` export of the parent
//! directory) because nfsd derives an export's file-handle ID from the
//! filesystem's volume UUID, and for ISO 9660 that UUID is just the image's
//! creation timestamp. Two ISOs built in the same second share it, and the
//! server then answers requests for one with the other's files (reproduced
//! in a VM: the second ISO read back the first one's content). An explicit
//! `fsid=` per export overrides the derived ID.

use crate::error::{PxeBootError, Result};
use std::collections::HashMap;
use std::path::Path;

/// Lowest `fsid` handed out. `fsid=0` is NFSv4's pseudo-root and small
/// numbers are what admins write by hand, so stay clear of both.
const FSID_MIN: u32 = 1000;

/// Stable `fsid` for an ISO, derived from its file name so it survives
/// reboots and re-mounts (a client holding a file handle across a service
/// restart keeps working, and the number doesn't depend on discovery order).
///
/// FNV-1a over the file name, folded into `FSID_MIN..2^31`.
pub fn fsid_for(file_name: &str) -> u32 {
    let mut hash: u32 = 0x811c_9dc5;
    for byte in file_name.as_bytes() {
        hash ^= u32::from(*byte);
        hash = hash.wrapping_mul(0x0100_0193);
    }
    FSID_MIN + hash % (0x8000_0000 - FSID_MIN)
}

/// `exports(5)` path escaping: whitespace and backslash are octal escapes.
fn escape_path(path: &Path) -> String {
    let mut out = String::new();
    for c in path.to_string_lossy().chars() {
        match c {
            ' ' => out.push_str("\\040"),
            '\t' => out.push_str("\\011"),
            '\\' => out.push_str("\\134"),
            _ => out.push(c),
        }
    }
    out
}

/// Renders the exports file for `(file_name, mount_path)` pairs.
///
/// Read-only to the given `clients` only. `insecure` allows source ports
/// above 1023: initramfs NFS clients are not guaranteed to bind a
/// privileged port, and the exports are read-only ISO contents on a
/// firewalled PXE network.
pub fn render_exports(isos: &[(String, &Path)], clients: &[String]) -> Result<String> {
    if clients.is_empty() {
        return Err(PxeBootError::Config(
            "NFS export needs at least one client network".into(),
        ));
    }

    let mut seen: HashMap<u32, &str> = HashMap::new();
    let mut out = String::from("# Generated by pxe-boot-prepare; rewritten on every run.\n");
    for (file_name, mount_path) in isos {
        if file_name.contains('\n') {
            return Err(PxeBootError::Config(format!(
                "ISO file name contains a newline, cannot be exported over NFS: {file_name:?}"
            )));
        }
        let fsid = fsid_for(file_name);
        if let Some(other) = seen.insert(fsid, file_name) {
            return Err(PxeBootError::Config(format!(
                "NFS fsid collision between {other} and {file_name} (both {fsid}); rename one"
            )));
        }
        let options = format!("ro,no_subtree_check,insecure,fsid={fsid}");
        let targets: Vec<String> = clients.iter().map(|c| format!("{c}({options})")).collect();
        out.push_str(&format!(
            "{} {}\n",
            escape_path(mount_path),
            targets.join(" ")
        ));
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    fn clients() -> Vec<String> {
        vec!["192.0.2.0/24".to_string()]
    }

    #[test]
    fn fsid_is_stable_for_the_same_name() {
        assert_eq!(fsid_for("ubuntu.iso"), fsid_for("ubuntu.iso"));
    }

    #[test]
    fn fsid_differs_between_names() {
        assert_ne!(fsid_for("a.iso"), fsid_for("b.iso"));
    }

    #[test]
    fn fsid_is_never_in_the_reserved_low_range() {
        for name in ["", "a", "ubuntu-26.04.1-desktop-amd64.iso", "rhel-10.2-x86_64-dvd.iso"] {
            let id = fsid_for(name);
            assert!(id >= FSID_MIN, "{name} -> {id}");
            assert!(id < 0x8000_0000, "{name} -> {id}");
        }
    }

    #[test]
    fn renders_one_read_only_export_per_iso_with_its_fsid() {
        let a = PathBuf::from("/run/pxe-boot/iso-mountpoint/a.iso");
        let b = PathBuf::from("/run/pxe-boot/iso-mountpoint/b.iso");
        let text = render_exports(
            &[("a.iso".into(), a.as_path()), ("b.iso".into(), b.as_path())],
            &clients(),
        )
        .unwrap();
        assert!(text.contains(&format!(
            "/run/pxe-boot/iso-mountpoint/a.iso 192.0.2.0/24(ro,no_subtree_check,insecure,fsid={})",
            fsid_for("a.iso")
        )));
        assert!(text.contains(&format!("fsid={}", fsid_for("b.iso"))));
        assert_eq!(text.lines().filter(|l| !l.starts_with('#')).count(), 2);
    }

    #[test]
    fn exports_are_never_writable() {
        let a = PathBuf::from("/m/a.iso");
        let text = render_exports(&[("a.iso".into(), a.as_path())], &clients()).unwrap();
        assert!(text.contains("(ro,"));
        assert!(!text.contains("rw"));
    }

    #[test]
    fn lists_every_client_network_on_the_line() {
        let a = PathBuf::from("/m/a.iso");
        let text = render_exports(
            &[("a.iso".into(), a.as_path())],
            &["192.0.2.0/24".to_string(), "198.51.100.0/24".to_string()],
        )
        .unwrap();
        let line = text.lines().find(|l| l.starts_with("/m/a.iso")).unwrap();
        assert!(line.contains("192.0.2.0/24(") && line.contains("198.51.100.0/24("));
    }

    #[test]
    fn escapes_spaces_in_the_exported_path() {
        let a = PathBuf::from("/m/my distro.iso");
        let text = render_exports(&[("my distro.iso".into(), a.as_path())], &clients()).unwrap();
        assert!(text.contains("/m/my\\040distro.iso "));
    }

    #[test]
    fn refuses_to_render_without_any_client_network() {
        let a = PathBuf::from("/m/a.iso");
        assert!(render_exports(&[("a.iso".into(), a.as_path())], &[]).is_err());
    }

    #[test]
    fn refuses_a_newline_in_an_iso_name() {
        let a = PathBuf::from("/m/a.iso");
        assert!(render_exports(&[("a\n.iso".into(), a.as_path())], &clients()).is_err());
    }

    #[test]
    fn two_distinct_isos_with_the_same_volume_date_still_get_distinct_fsids() {
        // The collision that motivated one-export-per-ISO: names stand in
        // for two ISOs sharing a build timestamp.
        assert_ne!(
            fsid_for("ubuntu-26.04.1-desktop-amd64.iso"),
            fsid_for("ubuntu-26.04.1-live-server-amd64.iso")
        );
    }
}
